test('keeps one export owner across formats and rejects wrong formats, replay, scan IDs and request IDs', async ({ page, plugin }, info) => {
  const first = await plugin.exported()
  const payload = await plugin.actualHost.report(first)
  const pending = await plugin.ui.locator('#report-status').textContent()
  await plugin.send({ ...payload, format: 'json', json: '{}' })
  await plugin.send({ ...payload, format: undefined })
  await plugin.send({ ...payload, scanId: first.scanId! + 1 })
  await plugin.send({ ...payload, requestId: first.requestId! + 1 })
  await plugin.send({ type: 'preflight-report', scanId: first.scanId, requestId: first.requestId, error: true, text: 'Wrong legacy JSON error' })
  expect(await plugin.resources()).toEqual([])
  await expect(plugin.ui.locator('#report-status')).toHaveText(pending!)
  await expect(plugin.button('json')).toBeDisabled()
  const download = page.waitForEvent('download')
  await plugin.send(payload)
  await save(await download, info, 'format-owner.html')
  await released(plugin)
  const json = await plugin.exported('json')
  await plugin.send({ ...payload, requestId: json.requestId })
  await expect(plugin.button()).toBeDisabled()
  const before = await plugin.resources()
  const jsonDownload = page.waitForEvent('download')
  const legacy = await plugin.actualHost.report(json)
  expect(legacy.format).toBeUndefined()
  await plugin.send(legacy)
  expect(JSON.parse((await save(await jsonDownload, info, 'legacy-json.json')).text).schemaVersion).toBe(1)
  await released(plugin)
  await plugin.send(payload)
  expect((await plugin.resources()).filter(event => event.type === 'create')).toHaveLength(before.filter(event => event.type === 'create').length + 1)
})

for (const trigger of ['rescan', 'page', 'mode', 'disconnect', 'new-scan'] as const) {
  test(`isolates pending HTML after ${trigger} and recovers only with a valid new scan`, async ({ plugin }) => {
    const request = await plugin.exported()
    const payload = await plugin.actualHost.report(request)
    if (trigger === 'rescan') {
      await plugin.ui.getByRole('button', { name: 'Rescan', exact: true }).click()
    }
    else if (trigger === 'page') {
      await plugin.send({ type: 'navigation-invalidated', scanId: request.scanId! + 1, text: 'Page changed. Rescan the new page.' })
    }
    else if (trigger === 'mode') {
      await plugin.ui.getByLabel('Connection mode').selectOption('github')
    }
    else if (trigger === 'disconnect') {
      await plugin.ui.getByRole('button', { name: 'Disconnect', exact: true }).click()
    }
    else {
      await plugin.actualHost.send({ type: 'rescan' })
      await plugin.send(plugin.actualHost.scan())
    }
    const feedback = await plugin.ui.locator('#report-status').textContent()
    await plugin.send(payload)
    expect(await plugin.resources()).toEqual([])
    await expect(plugin.ui.locator('#report-status')).toHaveText(feedback!)
    if (trigger !== 'new-scan') {
      await expect(plugin.button()).toBeDisabled()
      await expect(plugin.button('json')).toBeDisabled()
      await plugin.actualHost.send({ type: 'rescan', mode: trigger === 'mode' ? 'github' : 'console' })
      await plugin.send(plugin.actualHost.scan())
    }
    const current = await plugin.exported()
    await plugin.send({ type: 'preflight-report', format: 'html', scanId: current.scanId, requestId: current.requestId, error: true, rescan: true, text: 'This scan is no longer available. Rescan the page before exporting.' })
    await expect(plugin.button()).toBeDisabled()
    await expect(plugin.button('json')).toBeDisabled()
    expect(await plugin.resources()).toEqual([])
  })
}

for (const failure of ['blob', 'url', 'click'] as const) {
  test(`releases a failed HTML ${failure} download and retries with a fresh request`, async ({ page, plugin }, info) => {
    await plugin.failure(failure)
    const failed = await plugin.exported()
    await plugin.send(await plugin.actualHost.report(failed))
    await expect(plugin.ui.locator('#report-status')).toHaveText('Could not download the report. Try exporting again.')
    await expect(plugin.button()).toBeEnabled()
    await expect(plugin.button('json')).toBeEnabled()
    await released(plugin)
    await plugin.failure('')
    const retry = await plugin.exported()
    expect(retry.requestId).toBeGreaterThan(failed.requestId!)
    const download = page.waitForEvent('download')
    await plugin.send(await plugin.actualHost.report(retry))
    await save(await download, info, 'retried-report.html')
    await released(plugin)
    expect((await plugin.resources()).filter(event => event.type === 'create')).toHaveLength(failure === 'click' ? 2 : 1)
  })
}

