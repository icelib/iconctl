const longName = `${'设计系统'.repeat(42)} ${hostile}`
const pageName = `Icons ${hostile}`
const projectName = `Brand ${hostile}`

// Execute the built Figma host entry with a small sandbox API adapter. HTML is
// generated by the real immutable PreflightReport, never by a fixture renderer.
async function host() {
  const page: Node = { id: `page:${hostile}`, name: pageName, type: 'PAGE', children: [
    { id: '1:1', name: 'Arrow', type: 'COMPONENT', width: 16, height: 24 },
    { id: `1:${hostile}`, name: longName, type: 'COMPONENT', width: 48, height: 24 },
    { id: '1:3', name: `Draft<& ${hostile}`, type: 'COMPONENT', width: 16, height: 24 },
    { id: '1:4', name: 'Wide', type: 'COMPONENT', width: 48, height: 32 },
  ] }
  const stored = new Map<string, unknown>([
    ['iconctl-console-device', { origin: 'https://iconctl.icebreaker.top', deviceId: 'html-device-secret', projectId: 'project', token: 'html-device-token' }],
    ['iconctl-settings', { repo: 'secret/repo', token: 'html-github-token', eventType: 'html-private-event' }],
  ])
  const messages: Message[] = []
  const handlers = new Map<string, () => void>()
  const figma = {
    currentPage: page,
    showUI: () => {},
    ui: { postMessage: (message: Message) => messages.push(structuredClone(message)), onmessage: undefined as ((message: Message) => Promise<void>) | undefined },
    clientStorage: {
      getAsync: async (key: string) => stored.get(key),
      setAsync: async (key: string, value: unknown) => { stored.set(key, value) },
      deleteAsync: async (key: string) => { stored.delete(key) },
    },
    on: (name: string, callback: () => void) => handlers.set(name, callback),
    getNodeByIdAsync: async () => null,
    viewport: { scrollAndZoomIntoView: () => {} },
  }
  let context = { projectId: 'project', name: projectName, revision: 9, validate: { width: 16, height: 24, name: '^arrow$', skipPrefix: ['Draft<&'] }, namingMode: 'default' }
  const requests: string[] = []
  runInNewContext(await readFile('../../packages/figma-plugin/dist/code.js', 'utf8'), {
    figma,
    __html__: '',
    URL,
    Response,
    setTimeout,
    clearTimeout,
    fetch: async (input: string) => {
      requests.push(input)
      expect(input).toBe('https://iconctl.icebreaker.top/api/plugin/devices/html-device-secret/context')
      return Response.json(context)
    },
  })
  const send = async (message: Message) => figma.ui.onmessage!(message)
  await send({ type: 'load-settings' })
  await send({ type: 'console-status' })
  const scan = () => messages.filter(message => message.type === 'preflight').at(-1)!
  const report = async (request: Message) => {
    const before = messages.length
    await send(request)
    const result = messages.slice(before).find(message => message.type === 'preflight-report')
    expect(result).toBeDefined()
    return result!
  }
  return { page, requests, scan, report, send, close: () => handlers.get('close')!(), context: async (server: boolean) => {
    context = { ...context, namingMode: server ? 'server' : 'default' }
    await send({ type: 'console-status' })
  } }
}

const instrumentation = `<script>
  parent.__htmlResources = [];
  const record = (type, url) => parent.__htmlResources.push({ type, url });
  const create = URL.createObjectURL.bind(URL);
  const revoke = URL.revokeObjectURL.bind(URL);
  const click = HTMLAnchorElement.prototype.click;
  const NativeBlob = Blob;
  window.Blob = new Proxy(NativeBlob, { construct(target, args) {
    if (window.__htmlFailure === 'blob') throw new Error('fixture Blob failure');
    return Reflect.construct(target, args);
  }});
  URL.createObjectURL = (blob) => {
    if (window.__htmlFailure === 'url') throw new Error('fixture URL failure');
    const url = create(blob); record('create', url); return url;
  };
  URL.revokeObjectURL = (url) => { record('revoke', url); return revoke(url); };
  HTMLAnchorElement.prototype.click = function() {
    if (this.download) {
      record('click', this.href);
      if (window.__htmlFailure === 'click') throw new Error('fixture click failure');
    }
    return click.call(this);
  };
</script>`

async function plugin(page: Page) {
  const actualHost = await host()
  const messages: Message[] = []
  await page.exposeFunction('recordHtmlMessage', (message: Message) => messages.push(message))
  await page.setContent('<iframe title="Figma plugin" style="width:420px;height:560px"></iframe>')
  const html = (await readFile('../../packages/figma-plugin/dist/ui.html', 'utf8')).replace('<head>', `<head>${instrumentation}`)
  await page.evaluate((html) => {
    const frame = document.querySelector('iframe')!
    window.addEventListener('message', (event) => {
      if (event.source === frame.contentWindow && event.data.pluginMessage) {
        void (window as unknown as { recordHtmlMessage: (message: Message) => Promise<void> }).recordHtmlMessage(event.data.pluginMessage)
      }
    })
    frame.srcdoc = html
  }, html)
  const ui = page.frameLocator('iframe')
  await expect.poll(() => messages.some(message => message.type === 'rescan')).toBe(true)
  const send = (message: Message) => page.evaluate(message => new Promise<void>((resolve) => {
    const frame = document.querySelector('iframe')!.contentWindow!
    frame.addEventListener('message', () => resolve(), { once: true })
    frame.postMessage({ pluginMessage: message }, '*')
  }), message)
  await send(actualHost.scan())
  const requests = () => messages.filter(message => message.type === 'export-report')
  const button = (format = 'html') => ui.getByRole('button', { name: `Export ${format.toUpperCase()} report`, exact: true })
  const exported = async (format = 'html') => {
    const before = requests().length
    await button(format).click()
    await expect.poll(() => requests().length).toBe(before + 1)
    return requests().at(-1)!
  }
  const resources = () => page.evaluate(() => (window as unknown as { __htmlResources: Resource[] }).__htmlResources)
  const failure = (value: string) => ui.locator('body').evaluate((_element, value) => {
    (window as unknown as { __htmlFailure: string }).__htmlFailure = value
  }, value)
  return { ui, actualHost, send, button, exported, requests, resources, failure, messages }
}
type Plugin = Awaited<ReturnType<typeof plugin>>
const test = base.extend<{ plugin: Plugin }>({
  plugin: async ({ page }, use) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    const instance = await plugin(page)
    try {
      await use(instance)
      expect(errors).toEqual([])
    }
    finally {
      instance.actualHost.close()
    }
  },
})
async function save(download: Download, info: TestInfo, name: string) {
  expect(await download.failure()).toBeNull()
  const path = info.outputPath(name)
  await download.saveAs(path)
  return { path, text: await readFile(path, 'utf8') }
}
async function released(plugin: Plugin) {
  await expect.poll(async () => {
    const events = await plugin.resources()
    return events.filter(item => item.type === 'create').every(item => events.some(other => other.type === 'revoke' && item.url === other.url))
  }).toBe(true)
  await expect(plugin.ui.locator('a[download]')).toHaveCount(0)
}

