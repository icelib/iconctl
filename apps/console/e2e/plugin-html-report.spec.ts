  expect(html.text).not.toMatch(/html-device-secret|html-device-token|html-github-token|html-private-event|secret\/repo|Renamed after capture|Mutated after capture/)
  await released(plugin)
  const jsonRequest = await plugin.exported('json')
  const jsonDownload = page.waitForEvent('download')
  await plugin.send(await plugin.actualHost.report(jsonRequest))
  const json = await save(await jsonDownload, info, 'same-scan-report.json')
  const report = JSON.parse(json.text) as CapturedReport
  expect(report).toMatchObject({ schemaVersion: 1, page: { name: pageName }, project: { name: projectName, revision: 9 }, summary: { total: 4, checked: 3, skipped: 1, withIssues: 2, issueCount: 4 } })
  await released(plugin)
