interface Message {
  type: string
  scanId?: number
  requestId?: number
  format?: string
  html?: string
  json?: string
  [key: string]: unknown
}
interface CapturedReport {
  schemaVersion: number
  page: { name: string }
  rules: { name: string }
  items: { id: string, name: string, iconName: string | null, skipped: boolean, issues: string[] }[]
}
interface Node { id: string, name: string, type: string, width?: number, height?: number, children?: Node[] }
interface Resource { type: string, url?: string }
