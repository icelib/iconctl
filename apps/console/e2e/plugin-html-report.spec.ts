  // Changing the live host page after capture cannot alter either format.
  plugin.actualHost.page.name = 'Renamed after capture'
  plugin.actualHost.page.children![0]!.name = 'Mutated after capture'
  const download = page.waitForEvent('download')
  await plugin.send(captured)
  const file = await download
  expect(file.suggestedFilename()).toBe(`iconctl-preflight-${first.scanId}.html`)
  const html = await save(file, info, 'actual-host-report.html')
