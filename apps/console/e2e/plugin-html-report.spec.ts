    await expect(offline.locator('article')).toHaveCount(report.items.length)
    await expect(offline.locator('article h3')).toHaveText(report.items.map(item => item.name))
    await expect(offline.locator('.page-name')).toHaveText(report.page.name)
    await expect(offline).toHaveTitle(`${pageName} · iconctl preflight`)
    await expect(offline.locator('[data-injected], img, svg, script, iframe, link, form, a')).toHaveCount(0)
    await expect(offline.locator('meta[http-equiv="Content-Security-Policy"]')).toHaveAttribute('content', 'default-src \'none\'; style-src \'unsafe-inline\'; base-uri \'none\'; form-action \'none\'')
